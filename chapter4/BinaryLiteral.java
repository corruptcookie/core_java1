class BinaryLiteral
{
    public static void main(String[] args)
    {
        // How to use Binary Literal
        // int i = 5;
        int i = 0b101; // Can use 0b or 0B
        // Can use underscore to differentiate zeros (100_00_00_00_00)
        // int a = 0b1_00_00_00_00_00;
        System.out.println(i);
    }
}